"""Generate a real compiler dependency for one installation role, without I/O.

No PlatformIO option is invented and no Wi-Fi secrets are read or changed.
The generated header is local deployment configuration, not another firmware.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys


REPOSITORY = Path(__file__).resolve().parent.parent
MARKER = "// Generated by tools/configure_node.py; do not edit by hand."


def role_configuration(body_slot: str, config_path: Path,
                       legacy_alias_version: str | None = None) -> dict:
    config = json.loads(config_path.read_text(encoding="utf-8"))
    roles = {item["id"] for item in config["segments"]}
    supplied = body_slot
    if body_slot not in roles and body_slot != "unassigned":
        if legacy_alias_version != config.get("aliases_version"):
            raise ValueError("Unknown canonical body slot; legacy aliases require the exact --legacy-alias-version")
        body_slot = config.get("aliases", {}).get(body_slot)
        if body_slot not in roles:
            raise ValueError("Unknown body slot alias")
    if not re.fullmatch(r"[a-z][a-z0-9_]{0,31}", body_slot):
        raise ValueError("Body slot is not a safe firmware token")
    # Full config content is covered so role/layout revisions get a new version.
    canonical = json.dumps({"body_slot": body_slot, "layout": config},
                           ensure_ascii=True, sort_keys=True, separators=(",", ":"))
    digest = hashlib.sha256(canonical.encode("utf-8")).hexdigest()
    return {"body_slot": body_slot, "requested_slot": supplied,
            "config_version": "body-v1-" + digest[:16],
            "layout_version": config["schema_version"],
            "layout_sha256": hashlib.sha256(config_path.read_bytes()).hexdigest(),
            "alias_version": legacy_alias_version if supplied != body_slot else None}


def render_header(configuration: dict) -> str:
    return ("#pragma once\n" + MARKER + "\n"
            "// Device MAC and network role are intentionally independent.\n"
            f'// layout_sha256={configuration["layout_sha256"]}\n'
            f'#define IMU_BODY_SLOT "{configuration["body_slot"]}"\n'
            f'#define IMU_NODE_CONFIG_VERSION "{configuration["config_version"]}"\n')


def configure(body_slot: str, config_path: Path, firmware_dir: Path,
              legacy_alias_version: str | None = None, dry_run: bool = False,
              replace_existing: bool = False) -> dict:
    if not (firmware_dir / "platformio.ini").is_file():
        raise ValueError("Firmware directory must contain platformio.ini")
    configuration = role_configuration(body_slot, config_path, legacy_alias_version)
    target = firmware_dir / "include" / "node_config.h"
    content = render_header(configuration)
    original = target.read_text(encoding="utf-8") if target.exists() else None
    if original is not None and MARKER not in original and not replace_existing:
        raise ValueError("Existing node_config.h is user-managed; use --replace-existing only after reviewing it")
    changed = original != content
    if changed and not dry_run:
        target.parent.mkdir(parents=True, exist_ok=True)
        # Replacing the included header makes the role an actual build input.
        with target.open("w", encoding="utf-8", newline="\n") as stream:
            stream.write(content)
    return {**configuration, "header": str(target.resolve()), "changed": changed,
            "dry_run": dry_run, "physical_device_id": "derived from MAC at boot",
            "network_role": "unchanged: selected PlatformIO environment and Wi-Fi configuration"}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--body-slot", required=True)
    parser.add_argument("--config", type=Path, default=REPOSITORY / "host/config/body_v1.json")
    parser.add_argument("--firmware-dir", type=Path, default=REPOSITORY / "firmware")
    parser.add_argument("--legacy-alias-version")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--replace-existing", action="store_true")
    args = parser.parse_args(argv)
    try:
        result = configure(args.body_slot, args.config, args.firmware_dir,
                           args.legacy_alias_version, args.dry_run, args.replace_existing)
    except (ValueError, KeyError, OSError) as exc:
        parser.error(str(exc))
    print(json.dumps(result, ensure_ascii=True, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
